package xyz.felixb.dicebear.internal

/**
 * Uppercases [value] with full Unicode case mapping, matching `String.prototype.toUpperCase` of
 * the JavaScript reference. Code points whose JS mapping differs from a simple 1:1 mapping (or that
 * older Unicode tables do not know yet) come from the override table, the rest from the platform.
 */
internal fun jsToUpperCase(value: String): String {
    val out = StringBuilder(value.length)
    var i = 0
    while (i < value.length) {
        val c = value[i]
        val cp: Int
        val unit: String
        if (c.isHighSurrogate() && i + 1 < value.length && value[i + 1].isLowSurrogate()) {
            cp = ((c.code - 0xD800) shl 10) + (value[i + 1].code - 0xDC00) + 0x10000
            unit = value.substring(i, i + 2)
            i += 2
        } else {
            cp = c.code
            unit = c.toString()
            i++
        }
        out.append(UPPERCASE_OVERRIDES[cp] ?: unit.uppercase())
    }
    return out.toString()
}

